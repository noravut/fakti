/** ไฟล์ที่แก้เยอะกว่านี้ให้ตัดแล้วบอกจำนวนที่เหลือ prompt จะได้ไม่ยาวเกินอ่าน */
const QA_MAX_FILES = 40

/**
 * prompt ทวนงานหลังแก้เสร็จ — เติมหัว "เติมก่อนใช้" จากข้อมูลที่ fakti รู้
 * (defect กับไฟล์ที่เปลี่ยนจาก git) แล้วให้ agent เติมส่วนที่เหลือจาก context ของมันเอง
 * ผู้ใช้เห็นทั้งก้อนก่อนส่ง แก้ได้ทุกบรรทัด
 */
/** หัว "เติมก่อนใช้" ร่วมกันทั้ง QA แบบ defect และ feature — บรรทัดที่ต่างกันส่งเข้ามาเป็น work */
function qaHeader(title: string, work: string, changedFiles: string[]): string {
  const pad = '                  '
  const shown = changedFiles.slice(0, QA_MAX_FILES)
  const rest = changedFiles.length - shown.length
  const files = changedFiles.length > 0
    ? [...shown, ...(rest > 0 ? [`และอีก ${rest} ไฟล์ (ดู git diff)`] : [])].join(`\n${pad}`)
    : '(git ยังไม่เห็นไฟล์เปลี่ยน — สรุปเองจาก context ที่เพิ่งทำ)'

  return `# ${title}

## เติมก่อนใช้

  งานที่กำลังทำ:  ${work}

  ไฟล์ที่แก้:     ${files}

  วิธีเปิดระบบ:   สรุปเองจาก context ที่ทำก่อนหน้านี้

ก่อนเริ่ม ให้ทวนหัวข้อข้างบนกับสิ่งที่คุณเพิ่งทำจริงในบทสนทนานี้ ช่องไหนว่าง ไม่ครบ
หรือไม่ตรง ให้เติม/แก้ให้ถูกจากบริบทที่คุณมี แล้วเขียนสรุปที่เติมแล้วออกมาก่อนเริ่มรอบ QA`
}

/**
 * prompt ทวนงานหลังแก้เสร็จ — เติมหัว "เติมก่อนใช้" จากข้อมูลที่ fakti รู้
 * (defect กับไฟล์ที่เปลี่ยนจาก git) แล้วให้ agent เติมส่วนที่เหลือจาก context ของมันเอง
 * ผู้ใช้เห็นทั้งก้อนก่อนส่ง แก้ได้ทุกบรรทัด
 */
export function buildQaPrompt(defects: Defect[], changedFiles: string[]): string {
  const pad = '                  '
  const work = defects.length > 0
    ? defects.map(d => `${d.key}: ${d.title}`).join(`\n${pad}`)
    : '(ยังไม่มีข้อมูล — สรุปเองจาก context ที่เพิ่งทำ)'

  return `${qaHeader('QA Gate - ทวนงานที่ทำเสร็จแล้วก่อนส่งมอบ', work, changedFiles)}

${QA_ROLES}

${QA_STEP1_DEFECT}

${QA_STEPS_2_TO_4}

${QA_STEP5_DEFECT}

${QA_DEV_LOOP}

${QA_REPORT_DEFECT}`
}

/**
 * prompt ทวน feature — คนละคำถามกับ QA บั๊ก
 * บั๊กถามว่า "หายไหม ไม่ทำอย่างอื่นพังไหม" feature ถามว่า "ครบทุก REQ ไหม ตีความตรงไหม ไม่ทำเกินไหม"
 */
export function buildFeatureQaPrompt(feature: FeatureSpec, changedFiles: string[]): string {
  const pad = '                  '
  const work = `${feature.title}\n${pad}${requirementLines(feature).split('\n').join(`\n${pad}`)}`

  return `${qaHeader('ทวน requirement - ตรวจว่า feature ครบตามที่ขอก่อนส่งมอบ', work, changedFiles)}

${QA_ROLES}

${QA_STEP1_FEATURE}

${QA_STEPS_2_TO_4}

${QA_STEP5_FEATURE}

${QA_DEV_LOOP}

${QA_REPORT_FEATURE}`
}

