export function buildPrompt(defects: Defect[]): string {
  const blocks = defects.map(d => `
## ${d.key}: ${d.title}

${d.description}
`.trim()).join('\n\n')

  const isMulti = defects.length > 1

  return `${blocks}

---

ช่วยแก้ ${isMulti ? `defect ${defects.length} รายการนี้` : 'defect นี้'} ให้หน่อย

- หาต้นเหตุก่อน อย่าเพิ่งแก้อาการ ถ้าไม่แน่ใจว่าอยู่ตรงไหนให้ค้นในโค้ดก่อน
- เขียน test ที่ครอบเคสนี้ด้วยถ้า repo มี test อยู่แล้ว
- แก้ให้น้อยที่สุดเท่าที่จำเป็น อย่า refactor ส่วนอื่นแถมมา
- ห้ามเพิ่ม dependency ใหม่
${isMulti ? '- commit แยกทีละรายการ ใส่รหัส defect ใน commit message ด้วย\n' : ''}- ห้าม push

ถ้าข้อมูลไม่พอที่จะแก้ ให้บอกว่าขาดอะไรแล้วหยุด อย่าเดา`
}

/** รายการ REQ-n บรรทัดละข้อ — ใช้ทั้งใน prompt เริ่มงานและหัว QA */
function requirementLines(feature: FeatureSpec, indent = ''): string {
  return feature.requirements.map(r => `${indent}${r.key}: ${r.text}`).join('\n')
}

/**
 * prompt เริ่มงาน feature — requirement มาจากที่ผู้ใช้พิมพ์เอง ไม่ใช่ defect
 * "feature" ในที่นี้กว้าง: เพิ่ม แก้ ปรับ หรือตัดความสามารถก็ได้ ข้อความจึงไม่พูดว่า "ทำ feature ใหม่"
 * ต่างจากแก้บั๊กตรงที่เน้น "ครบทุกข้อ ไม่เกิน ไม่ตีความเอง"
 */
export function buildFeaturePrompt(feature: FeatureSpec): string {
  const context = feature.context?.trim()
  const nonGoals = feature.nonGoals?.length
    ? `\n## ไม่ทำ / ห้ามเปลี่ยน (ผู้สั่งงานระบุมา)\n\n${feature.nonGoals.map(n => `- ${n}`).join('\n')}\n`
    : ''

  return `# ${feature.title}
${context ? `\n${context}\n` : ''}
## สิ่งที่ต้องเป็นเมื่อทำเสร็จ

${requirementLines(feature, '- ')}
${nonGoals}
---

ช่วยทำให้ระบบเป็นตามรายการข้างบนให้หน่อย จะเป็นการเพิ่มความสามารถ แก้พฤติกรรม ปรับของเดิม
หรือตัดสิ่งที่ไม่ควรมีออก ก็ยึดตามที่เขียนไว้เป็นหลัก

รายการข้างบนคือสิ่งที่ผู้สั่งงานพิมพ์ได้ในเวลาสั้น ๆ ไม่ใช่ spec ที่ครบ
หน้าที่แรกของคุณคือทำให้มันเป็น spec ที่ตรวจได้ ก่อนเขียนโค้ดแม้แต่บรรทัดเดียว

${FEATURE_SPEC_STAGE}

${FEATURE_BUILD_STAGE}

${FEATURE_SELF_CHECK_STAGE}`
}

